package migrate

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/zoiko/zoikopay/internal/platform/db"
	"github.com/zoiko/zoikopay/internal/platform/idempotency"
	"github.com/zoiko/zoikopay/internal/platform/inbox"
	"github.com/zoiko/zoikopay/internal/platform/outbox"
)

// PlatformTables describes a module's standard platform tables.
type PlatformTables struct {
	Module     string // module directory, e.g. "payment"
	Schema     string // usually the module name
	WriterRole string // runtime role of the owning deployable, e.g. zp_execution
	RelayRole  string // usually zp_relay
}

var roleName = regexp.MustCompile(`^zp_[a-z]+$`)

// PlatformTablesSQL returns the content of a module's first migration: its
// schema, the idempotency registry, outbox, requeue log and inbox, with
// guards, row-level security and least-privilege grants. It is generated
// from the same Go definitions the platform code uses, so the two cannot
// drift; the generated file is then committed and checksummed like any other.
func PlatformTablesSQL(p PlatformTables) (string, error) {
	if !moduleName.MatchString(p.Module) || !moduleName.MatchString(p.Schema) {
		return "", fmt.Errorf("module and schema must match %s", moduleName)
	}
	if !roleName.MatchString(p.WriterRole) || !roleName.MatchString(p.RelayRole) {
		return "", fmt.Errorf("roles must match %s", roleName)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "-- +goose Up\n")
	fmt.Fprintf(&b, "-- Platform tables for module %q, generated by `go run ./cmd/migrate scaffold` (ADR 0005).\n", p.Module)
	fmt.Fprintf(&b, "-- Do not edit: once applied, the runner refuses changed files. Regenerate into a new version instead.\n")
	fmt.Fprintf(&b, "-- +goose StatementBegin\n")
	fmt.Fprintf(&b, "CREATE SCHEMA %s;\n", p.Schema)
	b.WriteString(db.SchemaUsageSQL(p.Schema, p.WriterRole, p.RelayRole))
	for _, part := range []string{
		idempotency.TableSQL(p.Schema), idempotency.GrantSQL(p.Schema, p.WriterRole),
		outbox.TableSQL(p.Schema), outbox.GrantSQL(p.Schema, p.WriterRole, p.RelayRole),
		inbox.TableSQL(p.Schema), inbox.GrantSQL(p.Schema, p.WriterRole),
	} {
		b.WriteString("\n" + strings.TrimSpace(part) + "\n")
	}
	fmt.Fprintf(&b, "-- +goose StatementEnd\n")
	return b.String(), nil
}
